import type { TestScope } from '../packages/engine/engine.entry-point.ts';
import { suite, test } from '../packages/test/test.entry-point.ts';
import {
    generatedCandidate,
    generatedValues,
    generatorContext,
    shrinkCandidates
} from '../test-support/generator-execution.ts';
import { gen } from './generators.ts';
import { prepareGenerator } from './generator.ts';

export const testNode = suite('generator primitives', [
    test('generates bounded primitive domains and scalar singletons', function (scope) {
        scope.assert.deepEqual(generatedValues(gen.integer({ min: 7, max: 7 }), 3, generatorContext(10, 2, 100)), [
            7,
            7,
            7
        ]);
        scope.assert.deepEqual(generatedValues(gen.bigint({ min: -2n, max: -2n }), 2, generatorContext(10, 2, 100)), [
            -2n,
            -2n
        ]);
        const booleans = generatedValues(gen.boolean(), 100, generatorContext(10, 2, 1000));
        scope.assert.deepEqual(new Set(booleans), new Set([ true, false ]));
        for (const value of [ null, undefined, false, 'fixed', 3n, -0, Number.NaN ]) {
            const [ generated ] = generatedValues(gen.constant(value), 1, generatorContext(10, 2, 100));
            scope.assert.equal(Object.is(generated, value), true);
        }
        return scope.assert.collect();
    }),
    test('generates integers and bigints within declared bounds', function (scope) {
        const integers = generatedValues(gen.integer({ min: -9, max: 13 }), 100, generatorContext(10, 2, 1000));
        scope.assert.equal(
            integers.every(function inRange(value) {
                return Number.isSafeInteger(value) && value >= -9 && value <= 13;
            }),
            true
        );
        const bigints = generatedValues(gen.bigint({ min: -100n, max: 2n }), 100, generatorContext(10, 2, 1000));
        scope.assert.equal(
            bigints.every(function inRange(value) {
                return value >= -100n && value <= 2n;
            }),
            true
        );
        return scope.assert.collect();
    }),
    test('retains exceptional doubles and restricts explicitly bounded doubles', function (scope) {
        const domain = prepareGenerator(gen.number(), generatorContext(10, 2, 100));
        for (
            const value of [
                Number.NaN,
                Number.NEGATIVE_INFINITY,
                Number.POSITIVE_INFINITY,
                -0,
                0,
                Number.MAX_VALUE
            ]
        ) {
            scope.assert.equal(domain.canShrinkWithoutContext(value), true);
        }
        const bounded = generatedValues(gen.number({ min: -0.5, max: 0.5 }), 100, generatorContext(10, 2, 1000));
        scope.assert.equal(
            bounded.every(function inRange(value) {
                return Number.isFinite(value) && value >= -0.5 && value <= 0.5;
            }),
            true
        );
        return scope.assert.collect();
    }),
    test('counts string lengths in UTF-16 units and admits lone surrogates', function (scope) {
        const domain = prepareGenerator(
            gen.string({ minLength: 1, maxLength: 3 }),
            generatorContext(2, 2, 100_000)
        );
        scope.assert.equal(domain.canShrinkWithoutContext('\u{D800}'), true);
        scope.assert.equal(domain.canShrinkWithoutContext('\u{DC00}'), true);
        scope.assert.equal(domain.canShrinkWithoutContext('😀'), true);
        scope.assert.equal(domain.canShrinkWithoutContext('abc'), false);
        for (let seed = 0; seed < 20; seed += 1) {
            const root = generatedCandidate(domain, seed);
            const values = [ root, ...shrinkCandidates(domain, root, 50) ];
            scope.assert.equal(
                values.every(function withinLength(value) {
                    return value.value.length > 0 && value.value.length <= 2;
                }),
                true
            );
        }
        return scope.assert.collect();
    }),
    test('caps default containers and gives bytes independent owned storage', function (scope) {
        scope.assert.deepEqual(generatedValues(gen.string(), 3, generatorContext(0, 0, 100)), [ '', '', '' ]);
        const bytes = generatedValues(gen.bytes({ minLength: 3, maxLength: 8 }), 10, generatorContext(4, 2, 1000));
        scope.assert.equal(
            bytes.every(function withinLength(value) {
                return value instanceof Uint8Array && value.length >= 3 && value.length <= 4 &&
                    value.buffer.byteLength === value.length;
            }),
            true
        );
        const buffers = new Set(bytes.map(function storage(value) {
            return value.buffer;
        }));
        scope.assert.equal(buffers.size, bytes.length);
        return scope.assert.collect();
    }),
    test('keeps generated byte buffers independent under mutation', function (scope: TestScope) {
        const bytes = generatedValues(gen.bytes({ minLength: 3, maxLength: 4 }), 2, generatorContext(4, 2, 1000));
        const first = bytes[0];
        const second = bytes[1];
        scope.require.defined(first);
        scope.require.defined(second);
        const retained = Array.from(second);
        first.fill(255);
        scope.assert.deepEqual(Array.from(second), retained);
        return scope.assert.collect();
    }),
    test('honors zero byte and string size caps', function (scope) {
        scope.assert.deepEqual(generatedValues(gen.string(), 3, generatorContext(0, 0, 100)), [ '', '', '' ]);
        const empty = generatedValues(gen.bytes(), 2, generatorContext(0, 0, 100));
        scope.assert.deepEqual(
            empty.map(function length(value) {
                return value.length;
            }),
            [ 0, 0 ]
        );
        return scope.assert.collect();
    }),
    test('rejects malformed numeric, length, and singleton domains at construction', function (scope) {
        for (const bounds of [ { min: 2, max: 1 }, { min: 0.5, max: 1 }, { min: 0, max: Number.MAX_VALUE } ]) {
            scope.assert.throws(function invalidInteger() {
                gen.integer(bounds);
            }, { name: 'RangeError' });
        }
        scope.assert.throws(function invalidNumber() {
            gen.number({ min: 0, max: Number.POSITIVE_INFINITY });
        }, { name: 'RangeError' });
        scope.assert.throws(function invalidBigint() {
            gen.bigint({ min: 1n, max: 0n });
        }, { name: 'RangeError' });
        return scope.assert.collect();
    }),
    test('rejects malformed container lengths', function (scope) {
        for (
            const bounds of [ { minLength: -1, maxLength: 1 }, { minLength: 2, maxLength: 1 }, {
                minLength: 0,
                maxLength: 1.5
            } ]
        ) {
            scope.assert.throws(function invalidString() {
                gen.string(bounds);
            }, { name: 'RangeError' });
            scope.assert.throws(function invalidBytes() {
                gen.bytes(bounds);
            }, { name: 'RangeError' });
        }
        return scope.assert.collect();
    }),
    test('rejects mutable constants and non-object bounds', function (scope) {
        for (
            const value of [ {}, [], Symbol('unsupported'), function () {
                return 1;
            } ]
        ) {
            scope.assert.throws(function invalidConstant() {
                Reflect.apply(gen.constant, undefined, [ value ]);
            }, { name: 'TypeError' });
        }
        for (const construct of [ gen.integer, gen.number, gen.bigint, gen.string, gen.bytes ]) {
            scope.assert.throws(function missingBounds() {
                Reflect.apply(construct, undefined, [ null ]);
            }, { name: 'TypeError' });
        }
        return scope.assert.collect();
    })
]);
